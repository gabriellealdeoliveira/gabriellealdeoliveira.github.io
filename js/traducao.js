const langSwitch = document.getElementById("lang-switch");
export let linguaAtual = localStorage.getItem("language") || "pt";

function traducaoPagina(language) {
    linguaAtual = language;

    document.querySelectorAll("[data-i18n]").forEach(e => {
        const key = e.dataset.i18n;
        if(traducoes[language][key]) {
            e.textContent = traducoes[language][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(e => {
        const key = e.dataset.i18nPlaceholder;
        if(traducoes[language][key]) {
            e.placeholder = traducoes[language][key];
        }
    });

    document.querySelectorAll("[data-i18n-value]").forEach(e => {
        const key = e.dataset.i18nValue;
        if(traducoes[language][key]) {
            e.value = traducoes[language][key];
        }
    });

    document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
    langSwitch.textContent = language === "pt" ? "EN" : "PT";
    localStorage.setItem("language", language);
}

if(langSwitch) {
    langSwitch.addEventListener("click", () => {
        linguaAtual = linguaAtual === "pt" ? "en" : "pt";
        traducaoPagina(linguaAtual);
    });
    
    traducaoPagina(linguaAtual);
}